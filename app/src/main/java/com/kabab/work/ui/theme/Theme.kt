/** Colours a project can be tagged with; [com.kabab.work.data.Project.colorIndex] indexes into this. */
val ProjectPalette: List<Color> = listOf(
    Color(0xFF4355B9), // indigo
    Color(0xFF00897B), // teal
    Color(0xFFE4572E), // orange
    Color(0xFF8E24AA), // purple
    Color(0xFF2E7D32), // green
    Color(0xFFC2185B), // pink
    Color(0xFF0277BD), // blue
    Color(0xFF6D4C41), // brown
)

fun projectColor(colorIndex: Int): Color = ProjectPalette[colorIndex.mod(ProjectPalette.size)]

@Composable
fun WorkTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colors = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }
    MaterialTheme(colorScheme = colors, content = content)
}
